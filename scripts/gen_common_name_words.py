#!/usr/bin/env python3
"""Regenerate crates/data/src/common_name_words.txt.

Words that appear in SEC company names (company_tickers.json titles) AND are ordinary
English words, first names, surnames or places (any case in /usr/share/dict/words, the
public-domain Webster's 2nd list on macOS), including simple inflections, plus a few
modern words the 1934 dictionary lacks. A company name made only of these words is
"word-like" and needs stock context before it counts as a news subject.

usage: scripts/gen_common_name_words.py <edgar.sqlite3> > crates/data/src/common_name_words.txt
"""
import re, sqlite3, sys

D = {w.strip().lower() for w in open("/usr/share/dict/words")}
MODERN = """crypto bitcoin ether online digital internet app apps software data cloud mobile email web
cyber smart solar wireless video media network networks tech fintech biotech global eco nano
streaming quantum robotics ai ok co paid winners computing marcus""".split()

def common(w):
    if w in D or w in MODERN:
        return True
    for suf, rep in (("ies", "y"), ("es", ""), ("s", ""), ("ed", ""), ("ed", "e"), ("ing", ""), ("ing", "e"), ("ers", ""), ("er", "")):
        if w.endswith(suf) and len(w) - len(suf) >= 3 and (w[: -len(suf)] + rep) in D:
            return True
    return False

db = sqlite3.connect(sys.argv[1])
tokens = set()
for (title,) in db.execute("select title from companies"):
    for w in re.split(r"[^a-z0-9]+", title.lower()):
        if len(w) >= 2 and not w.isdigit():
            tokens.add(w)
out = sorted(w for w in tokens if common(w)) + sorted(set(MODERN) - tokens)
print("# Generated by scripts/gen_common_name_words.py; one lowercase word per line.")
print("\n".join(sorted(set(out))))
